window.upsertZoneSceneDefinition = function upsertZoneSceneDefinition(zoneNumber, sceneDefinition) {
    const numericZoneNumber = Number(zoneNumber);
    if (!Number.isFinite(numericZoneNumber)) {
        return;
    }

    const existingDefinition = window.zoneScenesDatabase[numericZoneNumber] || {};
    window.zoneScenesDatabase[numericZoneNumber] = {
        ...existingDefinition,
        ...sceneDefinition,
        zones: Array.isArray(sceneDefinition?.zones) ? sceneDefinition.zones : (existingDefinition.zones || [])
    };
};
